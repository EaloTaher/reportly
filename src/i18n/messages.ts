type DeepString<T> = {
  [K in keyof T]: T[K] extends string ? string : DeepString<T[K]>
}

export type Messages = DeepString<(typeof dict)["ar"]>

export function getMessages(code: LanguageCode): Messages {
  return dict[code]
}

export function getDir(code: LanguageCode): "rtl" | "ltr" {
  return LANGUAGES.find((item) => item.code === code)?.dir ?? "rtl"
}

export function dateLocale(code: LanguageCode): string {
  return code === "ckb" ? "ckb-IQ" : "ar-IQ"
}
